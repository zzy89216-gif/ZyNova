《使用教程》

一、第一次启动
1. 看完并同意前面三份文档，再选择年龄段；
2. 进入首页后，如果没有实例，点「下载一个实例」；
3. 选择游戏版本（可加 Fabric / NeoForge / Quilt 加载器）→ 等待下载完成。

二、装模组 / 资源包 / 光影 / 整合包
「下载」页可选资源核心（Modrinth / CurseForge），会自动解析并安装前置依赖。
也可以在「文件管理」里把已经下好的文件放进对应目录；用「分享到 ZyNova」的方式丢进来会自动导入到 App 的 imported 目录。

三、联机
· 陶瓦联机：双方都装本启动器，进入同一房间即可（P2P，不需要开端口）；
· 樱花内网穿透：需要樱花账号与访问密钥。隧道类型固定 TCP，本机端口默认 25565 可改，
  游戏里「对局域网开放」后点「重新识别」会自动读端口；启动成功后页面顶部会出现地址，可一键复制。
  ⚠️ 公开宣传的服务器只能用「多线」节点，否则会被封号且不退款。

四、AI 助手
可以直接让它装游戏、装模组、读日志、改配置、做 Word/PPT（保存到 Download）。
联网固定使用 DuckDuckGo，可在设置里关闭；涉及删文件的操作会走回收站。

五、出问题了
1. 「设置 → 关于 → 日志」可以查看与导出日志；
2. 崩溃后可查看「崩溃报告」，或在 AI 对话里让它分析；
3. 反馈时请附上：设备型号、Android 版本、启动器版本、日志文件。

六、性能建议
· 内存不要超过设备可用内存的一半；
· 渲染器优先试 MobileGlues / LTW-Turbo，兼容性差再换 GL4ES；
· 大型整合包建议把游戏目录放在内部存储，并留足空间。

七、卸载与备份
卸载应用不会删除你外部存储上的游戏文件；删除实例请在应用内操作，避免残留。
升级前建议先导出一份整合包备份。
